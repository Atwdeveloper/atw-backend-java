package in.anytimework.atwbackend.shared.persistence;

import jakarta.persistence.Column;
import jakarta.persistence.EntityListeners;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import jakarta.persistence.Version;
import lombok.Getter;
import org.hibernate.annotations.UuidGenerator;
import org.springframework.data.annotation.CreatedBy;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.LastModifiedBy;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

import java.time.Instant;
import java.util.UUID;

/**
 * Base class for every persistent entity.
 *
 * <p>Provides, once and for all tables:
 * <ul>
 *   <li>a UUID primary key (generated by Hibernate on insert),</li>
 *   <li>created/updated audit stamps — who ({@code created_by}/{@code updated_by}) and
 *       when ({@code created_at}/{@code updated_at}), filled automatically,</li>
 *   <li>an optimistic-locking {@code version} column to prevent lost updates under concurrency.</li>
 * </ul>
 * Entities extend this and add only their own fields.</p>
 */
@Getter
@MappedSuperclass
@EntityListeners(AuditingEntityListener.class)
public abstract class BaseEntity {

    @Id
    @UuidGenerator
    @Column(name = "id", nullable = false, updatable = false)
    private UUID id;

    @CreatedDate
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @LastModifiedDate
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    @CreatedBy
    @Column(name = "created_by", updatable = false, length = 100)
    private String createdBy;

    @LastModifiedBy
    @Column(name = "updated_by", length = 100)
    private String updatedBy;

    @Version
    @Column(name = "version", nullable = false)
    private long version;

    /**
     * Identity is based on the primary key. Two entities are equal only once both have the
     * same non-null id; a transient (unsaved) entity is equal only to itself.
     */
    @Override
    public boolean equals(Object o) {
        if (this == o) {
            return true;
        }
        if (!(o instanceof BaseEntity other)) {
            return false;
        }
        return id != null && id.equals(other.id);
    }

    @Override
    public int hashCode() {
        // Constant per type: keeps hashCode stable across the id being assigned on persist.
        return getClass().hashCode();
    }
}
